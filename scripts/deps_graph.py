"""Write docs/architecture/deps.md: amber's module dependencies as a Mermaid graph (amber-7q0.3).

Each node is one entry of the layers contract in .importlinter (a module or subpackage), plus
the ``amber`` and ``amber.bundles`` package roots; nodes are grouped by layer, top first. The
graph draws an import only when no longer path implies it; a table lists every direct import,
including imports made only for type checking. Regenerate after changing imports between
modules, and review the diff:

    uv run --no-sync python scripts/deps_graph.py
"""

from __future__ import annotations

import configparser
import re
import sys
from pathlib import Path

import grimp

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs" / "architecture" / "deps.md"
CONTRACT = "importlinter:contract:layers"


def layers(config: Path) -> list[list[str]]:
    """The layers contract's modules, one list per layer, top first."""
    parser = configparser.ConfigParser(interpolation=None)
    parser.read(config)
    lines = parser[CONTRACT]["layers"].strip().splitlines()
    return [re.split(r"\s*[|:]\s*", line.strip()) for line in lines]


def _unit(module: str, units: list[str]) -> str:
    owners = [u for u in units if module == u or module.startswith(u + ".")]
    if owners:
        return max(owners, key=len)
    return "amber.bundles" if module.startswith("amber.bundles") else "amber"


def _node(unit: str) -> str:
    return unit.replace(".", "_")


def _reachable(start: str, edges: set[tuple[str, str]], skip: tuple[str, str]) -> set[str]:
    seen, frontier = set(), [b for a, b in edges if a == start and (a, b) != skip]
    while frontier:
        node = frontier.pop()
        if node not in seen:
            seen.add(node)
            frontier.extend(b for a, b in edges if a == node)
    return seen


def reduced(edges: set[tuple[str, str]]) -> set[tuple[str, str]]:
    """The edges no longer path implies."""
    return {(a, b) for a, b in edges if b not in _reachable(a, edges, skip=(a, b))}


def render(config: Path) -> str:
    stack = layers(config)
    units = [unit for layer in stack for unit in layer]
    graph = grimp.build_graph("amber")
    edges = {
        (_unit(importer, units), _unit(imported, units))
        for importer in graph.modules
        for imported in graph.find_modules_directly_imported_by(importer)
    } - {(unit, unit) for unit in [*units, "amber", "amber.bundles"]}
    lines = [
        "# Module dependencies",
        "",
        "Generated by `scripts/deps_graph.py` from the import graph; do not edit by hand. Each box",
        "is a layer of the `layers` contract in `.importlinter`, top first. An arrow is an import",
        "that no longer path implies; the table below lists every direct import, type-checking",
        "imports included. See [ADR 0001](../decisions/0001-dependency-layering.md).",
        "",
        "```mermaid",
        "flowchart TB",
        '    amber["amber"]',
        '    amber_bundles["amber.bundles"]',
    ]
    for level, layer in enumerate(stack, start=1):
        lines.append(f'    subgraph layer{level}["layer {level}"]')
        lines.extend(f'        {_node(unit)}["{unit}"]' for unit in layer)
        lines.append("    end")
    lines.extend(f"    {_node(a)} --> {_node(b)}" for a, b in sorted(reduced(edges)))
    lines += ["```", "", "| Module | Imports |", "|---|---|"]
    for importer in [*units, "amber", "amber.bundles"]:
        imported = sorted(b for a, b in edges if a == importer)
        if imported:
            lines.append(f"| `{importer}` | {', '.join(f'`{b}`' for b in imported)} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(render(ROOT / ".importlinter"))
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
